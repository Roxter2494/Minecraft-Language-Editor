const DICCIONARIOS: Record<IdiomaUi, Record<string, string>> = {
  es: ES,
  en: EN,
  'pt-BR': PT,
};

/**
 * Claves presentes en español (idioma de referencia) que faltan en cada
 * diccionario. Útil para comprobar que las traducciones están completas.
 */
export function clavesFaltantes(): Array<{ idioma: IdiomaUi; claves: string[] }> {
  const referencia = Object.keys(ES);
  return IDIOMAS_UI.filter((i) => i.codigo !== 'es').map((i) => ({
    idioma: i.codigo,
    claves: referencia.filter((clave) => !(clave in DICCIONARIOS[i.codigo])),
  }));
}

/** Normaliza un valor de configuración al idioma de interfaz admitido. */
export function normalizarIdiomaUi(valor: string | null | undefined): IdiomaUi {
  const v = (valor ?? '').trim().toLowerCase();
  if (v === 'en' || v === 'en-us' || v === 'english') return 'en';
  if (v === 'pt' || v === 'pt-br' || v === 'pt_br' || v === 'portugues') return 'pt-BR';
  return 'es';
}

/** Traduce una clave. Si falta, devuelve la clave tal cual. */
export function t(
  idioma: string | null | undefined,
  clave: string,
  vars?: Record<string, string | number>,
): string {
  const lang = normalizarIdiomaUi(idioma);
  const plantilla = DICCIONARIOS[lang][clave] ?? ES[clave] ?? clave;
  if (!vars) return plantilla;
  return plantilla.replace(/\{(\w+)\}/g, (todo, nombre: string) => {
    const valor = vars[nombre];
    return valor === undefined ? todo : String(valor);
  });
}
