const ORDENADAS = [...REGLAS].sort((a, b) => b[0].length - a[0].length);

/** Devuelve el color de la familia más específica o null si no hay color. */
export function colorDeClave(clave: string | null | undefined): string | null {
  if (!clave) return null;
  for (const [prefijo, color] of ORDENADAS) {
    if (clave.startsWith(prefijo)) return color;
  }
  return null;
}
